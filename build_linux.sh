#!/usr/bin/env bash
# ============================================================================
# build_linux.sh - cross-compile the Windows artifacts from Linux (mingw-w64)
#
#   ./build_linux.sh                 # version.dll + script.dll + console.dll
#   ./build_linux.sh proxy           # version.dll only
#   ./build_linux.sh script console  # selected plugins
#
# Toolchain (Ubuntu 24.04 / Debian 12 / Mint 22):
#   sudo apt install -y nasm g++-mingw-w64-x86-64 llvm
#
# What it does (Linux equivalent of build.bat + build_plugin.bat):
#   1. regenerate proxy/stubs.nasm from proxy/proxy_exports.h (17 forwards)
#   2. nasm -f win64   -> build/stubs.obj
#   3. clang/g++ --target-free mingw cross link -> *.dll
#   4. verify every artifact: PE32+ x86-64 and the expected export count
#
# Notes:
#   - stubs must be nasm: llvm-ml (MASM) is not packaged by Ubuntu.
#   - #pragma comment(lib, ...) is MSVC-only; every library is passed on the
#     command line instead, so the pragma warnings below are expected.
#   - -static avoids a libstdc++-6.dll / libgcc_s_seh-1.dll dependency, which
#     the host process would not have.
# ============================================================================
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BUILD="$ROOT/build"
CXX="${CXX:-x86_64-w64-mingw32-g++}"
NASM="${NASM:-nasm}"
# -shared is added per target; keep the common flags in one place.
COMMON=(-O2 -Wall -Wno-unknown-pragmas -shared -static -static-libgcc -static-libstdc++)

STUB_COUNT=0
ARTIFACTS=()

info()  { printf '\033[36m[*]\033[0m %s\n' "$*"; }
ok()    { printf '\033[32m[+]\033[0m %s\n' "$*"; }
warn()  { printf '\033[33m[!]\033[0m %s\n' "$*"; }
die()   { printf '\033[31m[x]\033[0m %s\n' "$*" >&2; exit 1; }

need() {
    command -v "$1" >/dev/null 2>&1 ||
        die "missing '$1' - install with: sudo apt install -y nasm g++-mingw-w64-x86-64 llvm"
}

# ---------------------------------------------------------------------------
# stubs: one  jmp [rel g_pfn_X]  per exported name, read from the X-macro list
# ---------------------------------------------------------------------------
gen_stubs() {
    local out="$BUILD/stubs.nasm"
    {
        echo '; auto-generated by build_linux.sh from proxy/proxy_exports.h'
        echo '; do not edit - the MSVC build uses stubs.asm instead'
        echo 'BITS 64'
        echo 'default rel'
        echo 'section .text'
    } >"$out"

    local fn n=0
    while IFS= read -r fn; do
        {
            echo ""
            echo "global $fn"
            echo "extern g_pfn_$fn"
            echo "$fn:"
            echo "    jmp [rel g_pfn_$fn]"
        } >>"$out"
        n=$((n + 1))
    done < <(sed -n 's/^[[:space:]]*X(\([A-Za-z0-9_]*\)).*/\1/p' \
        "$ROOT/proxy/proxy_exports.h")

    [ "$n" -gt 0 ] || die "no exports parsed out of proxy/proxy_exports.h"
    if grep -qE '^[[:space:]]*X\(' "$ROOT/proxy/proxy_exports.h"; then
        local declared
        declared=$(grep -cE '^[[:space:]]*X\(' "$ROOT/proxy/proxy_exports.h")
        [ "$declared" -eq "$n" ] || warn "parsed $n of $declared exports"
    fi

    STUB_COUNT=$n
    info "stubs: $n forwarding jumps -> ${out#"$ROOT"/}"
}

# ---------------------------------------------------------------------------
# verification: PE machine + export count
# ---------------------------------------------------------------------------
verify() {
    local dll="$1" expect="$2" name
    name="${dll#"$ROOT"/}"
    [ -f "$dll" ] || die "$name was not produced"

    file "$dll" | grep -q 'PE32+ executable' ||
        die "$name is not a PE32+ image: $(file -b "$dll")"

    local exports=0
    if command -v llvm-readobj >/dev/null 2>&1; then
        llvm-readobj --file-headers "$dll" | grep -q 'IMAGE_FILE_MACHINE_AMD64' ||
            die "$name is not x86-64"
        exports=$(llvm-readobj --coff-exports "$dll" | grep -c 'Name:' || true)
    elif command -v objdump >/dev/null 2>&1; then
        exports=$(objdump -p "$dll" | sed -n '/Export Address Table/,/^$/p' |
            grep -cE '^\s*\[[[:space:]]*[0-9]+\]' || true)
    else
        warn "neither llvm-readobj nor objdump found, export count skipped"
    fi

    if [ "$exports" -ne 0 ] && [ "$exports" -ne "$expect" ]; then
        die "$name exports $exports names, expected $expect"
    fi
    [ "$exports" -eq 0 ] || ok "$name: $exports export(s), $(stat -c%s "$dll") bytes"

    # A mingw -static build must not drag in the shared C++ runtime.
    if command -v objdump >/dev/null 2>&1; then
        if objdump -p "$dll" | grep -qiE 'DLL Name: (libstdc\+\+|libgcc_s)'; then
            die "$name depends on libstdc++/libgcc_s - add -static-libgcc -static-libstdc++"
        fi
    fi

    ARTIFACTS+=("$name")
}

# ---------------------------------------------------------------------------
# targets
# ---------------------------------------------------------------------------
build_proxy() {
    info "building version.dll (proxy)"
    "$NASM" -f win64 "$BUILD/stubs.nasm" -o "$BUILD/stubs.obj"
    "$CXX" "${COMMON[@]}" -I"$ROOT" \
        -o "$ROOT/proxy/version.dll" \
        "$ROOT/proxy/dllmain.cpp" "$BUILD/stubs.obj" "$ROOT/proxy/exports.def" \
        -luser32
    verify "$ROOT/proxy/version.dll" "$STUB_COUNT"
}

build_script() {
    info "building script.dll (plugin)"
    "$CXX" "${COMMON[@]}" -I"$ROOT/plugin" -I"$ROOT" \
        -o "$ROOT/plugin/script/script.dll" \
        "$ROOT/plugin/script/script_plugin.cpp" \
        -luser32 -lgdi32 -ld2d1 -ldwrite -lwinhttp
    verify "$ROOT/plugin/script/script.dll" 1
}

build_console() {
    info "building console.dll (plugin)"
    "$CXX" "${COMMON[@]}" -I"$ROOT/plugin" -I"$ROOT" \
        -o "$ROOT/plugin/console/console.dll" \
        "$ROOT/plugin/console/log_console.cpp" \
        -luser32 -lgdi32 -ld2d1 -ldwrite
    verify "$ROOT/plugin/console/console.dll" 1
}

# ---------------------------------------------------------------------------
# main
# ---------------------------------------------------------------------------
TARGETS=("$@")
[ ${#TARGETS[@]} -eq 0 ] && TARGETS=(proxy script console)

for t in "${TARGETS[@]}"; do
    case "$t" in
    proxy | script | console) ;;
    all) TARGETS=(proxy script console) ; break ;;
    -h | --help)
        sed -n '3,8p' "${BASH_SOURCE[0]}"
        exit 0
        ;;
    *) die "unknown target '$t' (proxy | script | console | all)" ;;
    esac
done

need "$CXX"
need "$NASM"
mkdir -p "$BUILD"

for t in "${TARGETS[@]}"; do
    case "$t" in
    proxy)
        # only the proxy needs the asm stubs
        if [ ! -s "$BUILD/stubs.obj" ] || [ "$ROOT/proxy/proxy_exports.h" -nt "$BUILD/stubs.obj" ]; then
            gen_stubs
        else
            info "stubs: up to date"
        fi
        build_proxy
        ;;
    script) build_script ;;
    console) build_console ;;
    esac
done

echo
ok "done: ${ARTIFACTS[*]}"
printf '   copy to Windows:  scp %s <user>@<host>:~/\n' "${ARTIFACTS[*]}"
